/// 'Master-Objekt' der API. Der Wrapper um Stationen, die den Beratungsverlauf tatsächlich beschreiben. Ein Vorgang kann dabei nicht nur ein Gesetz, sondern auch ein parlamentarischer Antrag sein.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(remote = "Self")]
pub struct Vorgang {
    pub api_id: uuid::Uuid,

    /// list of scraper uuids / key database ids that have touched this object
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    pub touched_by: Vec<models::TouchedByInner>,

    #[serde(deserialize_with = "de_string")]
    pub titel: String,

    #[serde(skip_serializing_if = "Option::is_none")]
    #[serde(deserialize_with = "de_optstring", default)]
    pub kurztitel: Option<String>,

    /// Nummer der Wahlperiode, in der der Vorgang stattfindet
    pub wahlperiode: u16,

    pub verfassungsaendernd: bool,

    pub typ: models::Vorgangstyp,

    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    pub ids: Vec<models::VgIdent>,

    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[schema(format = "uri")]
    #[serde(deserialize_with = "de_vecstring")]
    pub links: Vec<String>,

    /// Liste von Personen oder Organisationen, die den Vorgang initiiert haben. Kann z.B. eine Person, eine Organisation oder ein Gremium sein.
    pub initiatoren: Vec<models::Autor>,

    pub stationen: Vec<models::Station>,

    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    pub lobbyregister: Vec<models::Lobbyregeintrag>,
}
impl<'de> Deserialize<'de> for Vorgang {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let unchecked = Self::deserialize(deserializer)?;
        // constraint vorgang.links(format=uri)
        for link in &unchecked.links {
            if let Err(e) = axum::http::Uri::from_str(link) {
                return Err(de::Error::custom(e.to_string()));
            }
        }
        // check that no two stations have the exact same zp_start, rounded
        let unchecked = unchecked.with_round_timestamps();
        let mut fails = vec![];
        for i in 0..unchecked.stationen.len() {
            #[allow(
                clippy::arithmetic_side_effects,
                reason = "cannot be larger than .len()"
            )]
            for j in (i + 1)..unchecked.stationen.len() {
                let s1 = &unchecked.stationen[i];
                let s2 = &unchecked.stationen[j];
                if s1.typ != s2.typ && s1.zp_start == s2.zp_start {
                    fails.push(format!(
                        "({}/{}) and ({}/{})",
                        unchecked.stationen[i].typ,
                        unchecked.stationen[i].zp_start,
                        unchecked.stationen[j].typ,
                        unchecked.stationen[j].zp_start,
                    ));
                }
            }
        }
        if fails.is_empty() {
            Ok(unchecked)
        } else {
            Err(de::Error::custom(format!("Error: Some stations of different type have the exact same `zp_start` value.: {fails:?}\n
            This is not allowed because this value is used for imposing a total order on the stations for track validation.
                        Please modify these values to make clear which station comes first. For more details see https://codeberg.org/PaZuFa/pazufa-backend/issues/57.")))
        }
    }
}

