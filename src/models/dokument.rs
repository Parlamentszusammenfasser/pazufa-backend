    fn deserialize_enum() {
        let s: super::DokumentOrApiId =
            serde_json::from_str(include_str!("./../../tests/serialization/dokument.json"))
                .expect("Expected flawless serialization");
        assert!(matches!(s, super::DokumentOrApiId::Dokument(_)));
    }

