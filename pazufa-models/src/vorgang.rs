/// Entry of the Bundestagslobbyregister for a specific Vorgang
#[derive(Arbitrary, Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(remote = "Self")]
pub struct Lobbyregistereintrag {
    pub organisation: models::Autor,

    /// Internal ID within the register, necessary to build a url for it
    #[serde(deserialize_with = "Text::de")]
    #[arbitrary(with = Text::arb)]
    pub interne_id: String,

    /// Subject and reason for influencing the legislative process
    #[serde(deserialize_with = "Text::de")]
    #[arbitrary(with = Text::arb)]
    pub intention: String,

    /// direct link to the entry
    #[schema(format = "uri")]
    #[serde(deserialize_with = "Link::de")]
    #[arbitrary(with = Link::arb)]
    pub link: String,

    /// Array with associated Drucksachennummern.
    /// Is not crossreferenced in the database and just added as dataset
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub betroffene_drucksachen: Vec<String>,
}

/// The database allows only one entry per organisation and Vorgang
impl SetKey for Lobbyregistereintrag {
    type Key = models::Autor;
    fn key(&self) -> &models::Autor {
        &self.organisation
    }
}

impl std::fmt::Display for Lobbyregistereintrag {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let params: Vec<String> = vec![
            // Skipping organisation in query parameter serialization
            "interne_id".to_owned(),
            self.interne_id.clone(),
            "intention".to_owned(),
            self.intention.clone(),
            "link".to_owned(),
            self.link.clone(),
            "betroffene_drucksachen".to_owned(),
            self.betroffene_drucksachen.join(","),
        ];

        write!(f, "{}", params.join(","))
    }
}

/// In many ways a station is the heart of this API.
/// Every Vorgang consists of stations, which have only very few required fields.
/// They represent meaningful steps that any Vorgang takes from start to finish.
/// For further details, see the documentation.
#[derive(Arbitrary, Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(remote = "Self")]
pub struct Station {
    /// optional, here for future references. Is generated by the server. If you set it use UUID version 5 with your collector id as namespace
    #[serde(skip_serializing_if = "Option::is_none")]
    pub api_id: Option<uuid::Uuid>,

    /// list of scraper uuids / key database ids that have touched this object
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[arbitrary(default)]
    pub touched_by: Vec<models::TouchedByInner>,

    /// optional title, if other data does not provide a proper description
    #[serde(skip_serializing_if = "Option::is_none")]
    #[serde(deserialize_with = "Text::de_opt", default)]
    #[arbitrary(with = Text::arb_opt)]
    pub titel: Option<String>,

    /// Date of the first action within this station. i.e.: First session of a committee
    #[serde(deserialize_with = "Timestamp::de", default)]
    #[arbitrary(with = Timestamp::arb)]
    pub zp_start: chrono::DateTime<chrono::Utc>,

    /// Date of the last relevant action within this station. i.e.: last session of a committee
    #[serde(skip_serializing_if = "Option::is_none")]
    #[serde(deserialize_with = "Timestamp::de_opt", default)]
    #[arbitrary(with = Timestamp::arb_opt)]
    pub zp_modifiziert: Option<chrono::DateTime<chrono::Utc>>,

    pub gremium: models::Gremium,

    /// If the station if of type parl-ausschbsl, this field should be set if the committee is the main committee ('federführend')
    #[serde(skip_serializing_if = "Option::is_none")]
    pub gremium_federf: Option<bool>,

    /// Link to a web page describing this station in more detail, NOT to a pdf document
    #[schema(format = "uri")]
    #[serde(skip_serializing_if = "Option::is_none")]
    #[serde(deserialize_with = "Link::de_opt", default)]
    #[arbitrary(with = Link::arb_opt)]
    pub link: Option<String>,

    pub typ: models::Stationstyp,

    /// Currently unused. Always set to null
    #[serde(skip)]
    #[schema(minimum = 1, maximum = 10)]
    #[arbitrary(default)]
    pub trojanergefahr: Option<u8>,

    /// DEPRECATED: This has been moved to the Vorgang level.
    /// Please do not submit any data here, it will be merged as Vorgangs-Schlagworte
    /// For details, see <https://codeberg.org/PaZuFa/parlamentszusammenfasser/issues/54>
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "Text::de_vec")]
    #[arbitrary(with = Text::arb_vec)]
    pub schlagworte: Vec<String>,

    /// Documents that make up the Station or are associated with it.
    /// NOTE: At upload time, only complete documents are accepted;
    /// At download time, only the API IDs of the documents are passed down to the clients.
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub dokumente: Vec<models::DokumentOrApiId>,

    /// Further links to interesting infos for this station
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[schema(
        format = "uri",
        example = "https://example.com/video/of/plenary/session"
    )]
    #[serde(deserialize_with = "Link::de_vec")]
    #[arbitrary(with = Link::arb_vec)]
    pub additional_links: Vec<String>,

    /// List statement of interested parties
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub stellungnahmen: Vec<models::DokumentOrApiId>,

    /// Tiebreaker for Station ordering other than `zp_start`.
    /// If `zp_start(A)` > `zp_start(B)`, A > B;
    /// If `zp_start(A)` = `zp_start(B)`, `meta_tiebreaker` determines the order
    /// For more details, see <https://codeberg.org/PaZuFa/pazufa-backend/issues/57>
    #[serde(skip_serializing_if = "Option::is_none")]
    pub meta_tiebreaker: Option<u16>,
}
impl std::fmt::Display for Station {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let params: Vec<Option<String>> = vec![
            self.titel.as_ref().map(|titel| ["titel", titel].join(",")),
            self.gremium_federf
                .as_ref()
                .map(|gremium_federf| ["gremium_federf", &gremium_federf.to_string()].join(",")),
            self.link.as_ref().map(|link| ["link", link].join(",")),
            self.trojanergefahr
                .as_ref()
                .map(|trojanergefahr| ["trojanergefahr", &trojanergefahr.to_string()].join(",")),
            Some(["schlagworte".to_string(), self.schlagworte.join(",")].join(",")),
            Some(
                [
                    "additional_links".to_string(),
                    self.additional_links.join(","),
                ]
                .join(","),
            ),
        ];

        write!(
            f,
            "{}",
            params.into_iter().flatten().collect::<Vec<_>>().join(",")
        )
    }
}

/// Unique identifyer for a Vorgang within a parliament and election period: Vorgangsnummer, Initiativdrucksache, ...
#[derive(Arbitrary, Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
pub struct VgIdent {
    #[serde(deserialize_with = "Text::de")]
    #[arbitrary(with = Text::arb)]
    pub id: String,

    #[serde(deserialize_with = "Text::de")]
    #[arbitrary(with = Text::arb)]
    pub typ: String,
}

impl std::fmt::Display for VgIdent {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let params: Vec<String> = vec![
            "id".to_string(),
            self.id.clone(),
            "typ".to_string(),
            self.typ.clone(),
        ];
        write!(f, "{}", params.join(","))
    }
}

/// 'Master Object of the API. Wrapper type around stations.
/// `Vorgang` describes not only legislative processes, but also other kinds of parliamentary
/// proceedings
#[derive(Arbitrary, Debug, Clone, PartialEq, Serialize, Deserialize, ToSchema)]
#[serde(remote = "Self")]
pub struct Vorgang {
    /// The Api ID of this Vorgang
    /// Use UUID version 5 with your collector id as namespace
    /// ontrack(-)
    pub api_id: uuid::Uuid,

    /// list of scraper uuids / key database ids that have touched this object
    /// ontrack(meta)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[arbitrary(default)]
    pub touched_by: Vec<models::TouchedByInner>,

    /// Official Title of this Proceeding
    /// ontrack(-)
    #[serde(deserialize_with = "Text::de")]
    #[arbitrary(with = Text::arb)]
    pub titel: String,

    /// A brief, layman-understandable title of this law
    /// ontrack(-)
    #[serde(skip_serializing_if = "Option::is_none")]
    #[serde(deserialize_with = "Text::de_opt", default)]
    #[arbitrary(with = Text::arb_opt)]
    pub kurztitel: Option<String>,

    /// number of the electoral period
    /// ontrack(-)
    pub wahlperiode: u16,

    /// Is this Vorgang directly intended to change the constitution
    /// of whatever state it happens in?;
    /// ontrack(-)
    pub verfassungsaendernd: bool,

    /// The type of this Vorgang
    /// ontrack(-)
    pub typ: models::Vorgangstyp,

    /// Tuple of (typ, id)
    /// ontrack(-)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub ids: Vec<models::VgIdent>,

    /// Links that are associated with the Full Vorgang
    /// ontrack(refactor)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[schema(format = "uri")]
    #[serde(deserialize_with = "Link::de_vec")]
    #[arbitrary(with = Link::arb_vec)]
    pub links: Vec<String>,

    /// List of persons or organisations, which initiated the Vorgang
    /// ontrack(refactor)
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub initiatoren: Vec<models::Autor>,

    /// List of stations, the core of what happens in one Proceeding
    /// ontrack(-)
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub stationen: Vec<models::Station>,

    /// Lobbyregister annotations from Bundestag sources
    /// ontrack(refactor)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "KeyedSet::de")]
    #[arbitrary(with = KeyedSet::arb)]
    pub lobbyregister: Vec<models::Lobbyregistereintrag>,

    /// Sachgebiet information
    /// ontrack(at-least-one)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "Set::de")]
    #[arbitrary(with = Set::arb)]
    pub sachgebiete: Vec<Sachgebiet>,

    /// General Vorgangs-Schlagworte
    /// ontrack(at-least-one)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "Text::de_vec")]
    #[arbitrary(with = Text::arb_vec)]
    pub schlagworte: Vec<String>,

    /// Ressort. Skipped if None
    /// ontrack(mandatory)
    #[serde(skip_serializing_if = "Option::is_none")]
    pub ressort: Option<Ressort>,

    /// Summary of the whole Vorgang's idea
    /// See parlamentszusammenfasser#55
    /// ontrack(at-least-one)
    #[serde(skip_serializing_if = "Vec::is_empty", default = "Vec::new")]
    #[serde(deserialize_with = "KeyedSet::de")]
    #[arbitrary(with = KeyedSet::arb)]
    pub zusammenfassung: Vec<Zusammenfassungstupel>,
}

impl std::default::Default for Vorgang {
    fn default() -> Self {
        Self {
            api_id: uuid::Uuid::nil(),
            touched_by: vec![],
            titel: "DEFAULT".to_string(),
            kurztitel: None,
            schlagworte: vec![],
            wahlperiode: 0,
            verfassungsaendernd: false,
            typ: models::Vorgangstyp::Sonstig,
            ids: vec![],
            links: vec![],
            initiatoren: vec![],
            stationen: vec![],
            lobbyregister: vec![],
            ressort: None,
            sachgebiete: vec![],
            zusammenfassung: vec![],
        }
    }
}

impl std::fmt::Display for Vorgang {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        let params: Vec<Option<String>> = vec![
            Some("titel".to_string()),
            Some(self.titel.clone()),
            self.kurztitel
                .as_ref()
                .map(|kurztitel| ["kurztitel", kurztitel].join(",")),
            Some("wahlperiode".to_string()),
            Some(self.wahlperiode.to_string()),
            Some("verfassungsaendernd".to_string()),
            Some(self.verfassungsaendernd.to_string()),
            Some(["links".to_string(), self.links.join(",")].join(",")),
        ];

        write!(
            f,
            "{}",
            params.into_iter().flatten().collect::<Vec<_>>().join(",")
        )
    }
}

